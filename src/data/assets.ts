export const assetsById = Object.fromEntries(assets.map((a) => [a.id, a])) as Record<
  string,
  Asset
>;

export const assetsByFilename = Object.fromEntries(
  assets.map((a) => [a.filename, a]),
) as Record<string, Asset>;

/** Assets allowed in public UI (excludes hold). Reserve is listed but not auto-bundled. */
export function getPublicAssets(): Asset[] {
  return assets.filter((a) => a.status !== 'hold');
}

export function getActiveAssets(): Asset[] {
  return assets.filter((a) => a.status === 'active');
}

export function getAssetsForScene(sceneId: Asset['sceneIds'][number]): Asset[] {
  return assets.filter(
    (a) => a.status === 'active' && a.sceneIds.includes(sceneId),
  );
}

